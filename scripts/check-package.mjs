import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import JSZip from 'jszip';

const manifest = JSON.parse(await fs.readFile('extension.json', 'utf8'));
const filename = `build/dist/${manifest.name}_v${manifest.version}.eext`;
const zip = await JSZip.loadAsync(await fs.readFile(filename), { checkCRC32: true });
const html = await zip.file('iframe/index.html').async('string');
assert.ok(html.includes('document.body.dataset.started'));
assert.ok(!html.includes('src="/iframe/app.js"'));
assert.ok(html.includes('<style>'));
assert.ok(html.includes('route-spacing-command-v3'));
assert.ok(html.includes('route-spacing-state-v3'));
assert.ok(html.includes('推挤走线'));
assert.ok(html.includes('id="scope"'));
assert.ok(html.includes('id="clearanceSource"'));
assert.ok(html.includes('PCB规则'));
assert.ok(html.includes('id="compatible"'));
assert.ok(html.includes('兼容模式'));
assert.ok(html.includes('value="auto"'));
assert.ok(html.includes('所选导线的图层属性'));
assert.ok(html.includes('getCurrentTheme'));
assert.ok(html.includes('prefers-color-scheme:dark'));
assert.ok(html.includes('独立线段'));
assert.ok(html.includes('联动两端连接段'));
assert.ok(html.includes('45°过渡'));
assert.ok(!html.includes('与区外连接可能断开'));
assert.ok(!html.includes('<canvas'));
for (const match of html.matchAll(/<script>([\s\S]*?)<\/script>/g))
	new vm.Script(match[1]);
const ids = manifest.headerMenus.pcb.flatMap(m => [m.id, ...m.menuItems.map(i => i.id)]);
assert.equal(ids.length, new Set(ids).size);
assert.ok((await zip.file('dist/index.js').async('string')).includes('openPanel'));
assert.ok((await zip.file('dist/index.js').async('string')).includes('applyRoutes'));
assert.ok((await zip.file('dist/index.js').async('string')).includes('route-spacing-journal-v1'));
assert.ok((await zip.file('dist/index.js').async('string')).includes('getCurrentRuleConfiguration'));
assert.ok((await zip.file('dist/index.js').async('string')).includes('getNetRules'));
assert.ok(!(await zip.file('dist/index.js').async('string')).includes('宿主写入的坐标与目标不一致'));
assert.ok(!Object.keys(zip.files).some(path => path.startsWith('validation/')));
await fs.mkdir('validation', { recursive: true });
const report = { filename, version: manifest.version, inlineHTMLBytes: Buffer.byteLength(html), crcPassed: true, scriptSyntaxPassed: true, menuIdsUnique: true };
await fs.writeFile('validation/package.json', JSON.stringify(report, null, 2));
console.info(report);
